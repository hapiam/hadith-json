  BookPaths('bukhari', 'db/unified/by_book/bukhari.json', 'bukhari'),
  BookPaths('muslim', 'db/unified/by_book/muslim.json', 'muslim'),
  BookPaths('nasai', 'db/unified/by_book/nasai.json', 'nasai'),
  BookPaths('abudawud', 'db/unified/by_book/abudawud.json', 'abudawud'),
