// STAGE: verification/report tool, repeatable — cross-checks the amrayn.com
// "scrape 1.0" processed files (sources/amrayn.com/processed/*.json) against
// our own canonical spine (db/by_book/**/*.json), never modifies either
// side. Run any time either side changes to refresh the comparison.
//
// INPUT: sources/amrayn.com/processed/{book}.json (built by
// sources/amrayn.com/scripts/build_processed.dart) + db/unified/by_book/
// {bookKey}.json — this repo's own definition of canonical (see README.md's
// "Canonical data: db/unified/" section); `db/by_book/` is the OLDER,
// pre-multilingual-merge spine kept only for compatibility, not what this
// script means by "canonical". Both carry the same idInBook/reference/
// arabic fields for the books amrayn covers (unified only adds the
// `translations` map on top), so which one is used doesn't change the
// comparison numbers below — just which is honest to call canonical.
//
// OUTPUT: sources/amrayn.com/COMPARISON_REPORT.md — per-book counts of
// what each side HAS that the other is missing (existence gaps), plus each
// side's own "entry exists but content is blank" stub count, so a future
// gap-filling pass knows exactly where to look without re-deriving this.
//
// Matching key: amrayn's own `citation` field (or idInBook when there's no
// letter suffix) against a normalized citation pulled from canonical's
// `reference.text`/`reference.url` — both sides ultimately trace to the
// same sunnah.com-style numbering, so a matching key should represent the
// same hadith on both sides. Malik is the one exception: neither side's
// citation string round-trips cleanly through Malik's chapter-local URL
// scheme, so it's matched on (chapter, local#) directly from each side's
// own dedicated fields instead.
import 'dart:convert';
import 'dart:io';

class BookPaths {
  const BookPaths(this.amraynKey, this.canonicalPath, this.canonicalKey);
  final String amraynKey;
  final String canonicalPath;
  final String canonicalKey;
}

